"""
make-sounds.py — synthesises SplitFree's starter sound effects from scratch.

Because they're generated by this script (no samples), they're free to use
anywhere. Want different sounds? Just replace the .mp3 files in
assets/sounds/ with your own (keep the same file names).

Run from the project root:  python3 scripts/make-sounds.py
Needs: numpy, and ffmpeg on your PATH (to convert to small mp3 files).
"""
import os
import subprocess
import wave

import numpy as np

RATE = 44100
OUT = 'assets/sounds'


def t(seconds):
    return np.linspace(0, seconds, int(RATE * seconds), endpoint=False)


def env(n, attack=0.005, decay=8.0):
    """Quick fade-in, then exponential fade-out."""
    x = np.arange(n) / RATE
    a = np.minimum(1, x / attack)
    return a * np.exp(-decay * x)


def tone(freq, seconds, decay=8.0, harmonics=(1, 0.5, 0.25), wave_type='sine'):
    x = t(seconds)
    sig = np.zeros_like(x)
    for i, amp in enumerate(harmonics, start=1):
        if wave_type == 'saw':
            sig += amp * (2 * ((freq * i * x) % 1) - 1)
        else:
            sig += amp * np.sin(2 * np.pi * freq * i * x)
    return sig * env(len(x), decay=decay)


def smooth(x, width):
    """A crude low-pass filter: average each sample with its neighbours."""
    return np.convolve(x, np.ones(width) / width, mode='same')


def place(track, sound, at):
    start = int(at * RATE)
    end = min(len(track), start + len(sound))
    track[start:end] += sound[: end - start]


def save(name, sig):
    sig = sig / (np.max(np.abs(sig)) + 1e-9) * 0.6  # normalise, keep it fairly quiet
    pcm = (sig * 32767).astype(np.int16)
    wav_path = f'{OUT}/{name}.wav'
    with wave.open(wav_path, 'wb') as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(RATE)
        w.writeframes(pcm.tobytes())
    subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-i', wav_path, '-b:a', '64k', f'{OUT}/{name}.mp3'], check=True)
    os.remove(wav_path)


rng = np.random.default_rng(7)

# 💸 Ka-ching: a drawer click, then two bright bell hits.
track = np.zeros(int(RATE * 0.7))
place(track, smooth(rng.standard_normal(int(RATE * 0.03)), 3) * env(int(RATE * 0.03), decay=120) * 0.6, 0.0)
place(track, tone(2093, 0.6, decay=6, harmonics=(1, 0.6, 0.3, 0.2)), 0.06)
place(track, tone(2637, 0.6, decay=6, harmonics=(1, 0.6, 0.3, 0.2)), 0.14)
save('add-expense', track)

# 🎉 Ta-da: a quick rising arpeggio landing on a held chord.
track = np.zeros(int(RATE * 0.9))
for i, f in enumerate([523.25, 659.25, 783.99]):
    place(track, tone(f, 0.15, decay=10, wave_type='saw', harmonics=(0.6,)), i * 0.07)
for f in [523.25, 659.25, 783.99, 1046.5]:
    place(track, smooth(tone(f, 0.6, decay=3, wave_type='saw', harmonics=(0.4,)), 6), 0.21)
save('settle-up', track)

# 👀 Ding-dong: a doorbell for nudges.
track = np.zeros(int(RATE * 0.9))
place(track, tone(659.25, 0.5, decay=5, harmonics=(1, 0.3)), 0.0)
place(track, tone(523.25, 0.6, decay=4, harmonics=(1, 0.3)), 0.3)
save('nudge', track)

# 🗑️ Whoosh: noise that sweeps from low to high and fades.
n = int(RATE * 0.4)
noise = rng.standard_normal(n)
sweep = np.concatenate([smooth(chunk, w) for chunk, w in zip(np.array_split(noise, 20), np.linspace(40, 2, 20).astype(int))])
shape = np.sin(np.linspace(0, np.pi, n)) ** 2
save('delete', sweep * shape)

# 🎺 Sad trombone: wah... wah... wah... waaaah (with a wobble on the last note).
track = np.zeros(int(RATE * 1.9))
notes = [(293.66, 0.0, 0.3), (277.18, 0.35, 0.3), (261.63, 0.7, 0.3), (246.94, 1.05, 0.8)]
for f, at, dur in notes:
    x = t(dur)
    wobble = 1 + (0.02 * np.sin(2 * np.pi * 6 * x) if dur > 0.5 else np.zeros_like(x))
    phase = np.cumsum(f * wobble) / RATE
    saw = 2 * (phase % 1) - 1
    shape = np.minimum(1, x / 0.04) * np.minimum(1, (dur - x) / 0.08)
    place(track, smooth(saw, 12) * shape, at)
save('roast', track)

print('sounds written to', OUT)
